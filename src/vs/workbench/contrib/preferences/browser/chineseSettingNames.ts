import { getNLSLanguage } from '../../../../nls.js';

export function useChineseSettingNames(): boolean {
	const locale = getNLSLanguage();
	return locale === 'zh-cn' || locale === 'zh-hans' || locale === 'zh-sg';
}

export function chineseSettingTitle(key: string): string | undefined {
	return Object.hasOwn(titles, key) ? titles[key] : undefined;
}

export function chineseSettingCategory(category: string): string {
	return category.split('.').filter(Boolean).map(part => Object.hasOwn(categories, part) ? categories[part] : part).join(' › ');
}

